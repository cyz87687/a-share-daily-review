def _code_of(windcode: str) -> str:
    return windcode.split(".")[0]


def main():
    snap = {}
    for batch in RAW_BATCHES:
        for row in batch["rows"]:
            windcode = row[-1]
            snap[_code_of(windcode)] = {
                "open": float(row[4]) if row[4] not in ("", None) else None,
                "close": float(row[3]) if row[3] not in ("", None) else None,
            }

    df = pd.read_csv(CSV, dtype={"代码": str}, encoding="utf-8-sig")
    filled_open = filled_close = 0
    for i, row in df.iterrows():
        code = str(row["代码"]).zfill(6)
        if code in snap:
            s = snap[code]
            if s["open"] is not None:
                df.at[i, "次日开盘表现"] = round(s["open"], 2)
                filled_open += 1
            if s["close"] is not None:
                df.at[i, "次日收盘表现"] = round(s["close"], 2)
                filled_close += 1
    df.to_csv(CSV, index=False, encoding="utf-8-sig")
    print(f"回填完成：开盘 {filled_open}/60，收盘 {filled_close}/60 -> {CSV}")


if __name__ == "__main__":
    main()
